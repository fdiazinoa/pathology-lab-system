create table public.organs (
    id bigint generated by default as identity primary key,
    code text generated always as ('ORG-' || lpad(id::text, greatest(4, length(id::text)), '0')) stored unique,
    name text not null check (length(trim(name)) > 0),
    procedure_type text not null check (procedure_type in ('Biopsia','Citología','Líquido')),
    original_code text,
    section_code text,
    source_record jsonb not null default '{}'::jsonb,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);
alter table public.organs enable row level security;
revoke all on public.organs from public, anon, authenticated;
grant select, insert, update, delete on public.organs to authenticated;
grant all on public.organs to service_role;
revoke all on sequence public.organs_id_seq from public, anon, authenticated;
grant usage on sequence public.organs_id_seq to authenticated;
grant all on sequence public.organs_id_seq to service_role;
create policy "Approved staff read organs" on public.organs for select to authenticated
using (exists (select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_active and p.role in ('admin','pathologist','technician','courier')));
create policy "Administrators manage organs" on public.organs for all to authenticated
using (exists (select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_active and p.role='admin'))
with check (exists (select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_active and p.role='admin'));
